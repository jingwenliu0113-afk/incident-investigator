def _write(root: Path) -> None:
    from baselines.statistical import predict
    from collect.labels import check_label
    from collect.normalize import NormalizeInputs, normalize
    from collect.policy import POLICY_SHA256, load_policy
    from collect.rawfile import scan_raw_file
    from collect.snapshot import open_snapshot
    from eval.score import check_prediction

    policy = load_policy()
    if policy.raw.get("status") != "frozen" or policy.sha256 != POLICY_SHA256:
        raise PermissionError(f"the sample is normalized with the frozen, pinned policy only (got {policy.sha256})")
    layout = DataLayout(root)
    with tempfile.TemporaryDirectory(prefix="ii-sample-") as work:
        files = write_raw(Path(work) / "raw")
        scans = {sig: scan_raw_file(path, sig) for sig, path in files.items()}
        inputs = NormalizeInputs(raw_dir=Path(work) / "raw", raw_sha256={s: scan["sha256"] for s, scan in scans.items()},
                                 raw_duplicates={s: scan["duplicates"] for s, scan in scans.items()},
                                 window_host=WINDOW, clock_offsets=[0.0, 0.0])
        normalize(inputs, policy, incident_dir=layout.incident_dir(INCIDENT),
                  report_path=layout.normalize_report_path(INCIDENT), staging_dir=Path(work) / "staging", code=None)

    inj, lab = injection(), label()
    if problems := check_label(lab, inj, services=policy.sut_services):
        raise ValueError(f"the sample label fails its checks: {problems}")
    layout.run_group_truth_dir(RUN_GROUP).mkdir(parents=True)
    layout.injection_path(RUN_GROUP).write_text(json.dumps(inj, indent=2) + "\n")
    layout.label_path(INCIDENT).write_text(json.dumps(lab, indent=2) + "\n")

    pred = predict(open_snapshot(layout.incident_dir(INCIDENT) / "normalized", layout), INCIDENT)
    pred["usage"]["latency_s"] = None  # wall time: the one value that is not reproducible
    if problems := check_prediction(pred):
        raise ValueError(f"the example prediction is invalid: {problems}")
    (root / PREDICTION).parent.mkdir(parents=True)
    (root / PREDICTION).write_text(json.dumps(pred, indent=2) + "\n")
    (root / "README.md").write_text(README)

    from env.lock import sha256_path

    listed = [{"path": p.relative_to(root).as_posix(), "bytes": p.stat().st_size, "sha256": sha256_path(p)}
              for p in sorted(root.rglob("*")) if p.is_file()]
    manifest = {"sample_version": 1, "synthetic": True, "note": NOTE, "generator": {**GENERATOR, "seed": SEED},
                "incident_id": INCIDENT, "run_group_id": RUN_GROUP, "window": list(WINDOW),
                "regenerate": f"uv run python -m collect sample --out {SAMPLE_DIR.as_posix()} --replace",
                "demo": "uv run python -m eval demo", "files": listed}
    (root / SAMPLE_FILE).write_text(json.dumps(manifest, indent=2) + "\n")


def is_sample(root: Path) -> bool:
    """Does `root` hold a sample this generator wrote (its manifest says synthetic and names this generator)?"""
    try:
        manifest = json.loads((Path(root) / SAMPLE_FILE).read_text())
    except (OSError, ValueError):
        return False
    return manifest.get("synthetic") is True and (manifest.get("generator") or {}).get("name") == GENERATOR["name"]


def unlisted_files(root: Path) -> list[str]:
    """Files under `root` that its sample.json does not list (besides sample.json and what Finder writes)."""
    root = Path(root)
    listed = {e.get("path") for e in json.loads((root / SAMPLE_FILE).read_text()).get("files", [])} | {SAMPLE_FILE}
    return sorted(rel for p in root.rglob("*") if p.is_file() and p.name not in OS_FILES
                  and (rel := p.relative_to(root).as_posix()) not in listed)


def _fold(parts) -> list[str]:
    return [unicodedata.normalize("NFC", part).casefold() for part in parts]


def inside(path: Path, root: Path) -> bool:
    """Is `path` the directory `root` or under it, however it is spelled? resolve() follows links but keeps case, and APFS
    ignores case (data/EXTERNAL is data/external), so names are compared case- and normalization-insensitively (refused on
    a case-sensitive file system too: conservative) and, from the nearest existing directories, by inode (firmlinks)."""
    path, root = Path(path).resolve(), Path(root).resolve()
    if _fold(path.parts)[:len(root.parts)] == _fold(root.parts):
        return True
    anchor = next(p for p in (root, *root.parents) if p.exists())
    below = _fold(root.parts[len(anchor.parts):])
    return any(p.exists() and os.path.samefile(p, anchor) and _fold(path.parts[len(p.parts):])[:len(below)] == below
               for p in (path, *path.parents))


def generate(out: Path, *, replace: bool = False, project_dir: Path | None = None) -> dict:
    """Write the sample to `out`, never in `project_dir`/data/external (decision 027). An existing `out` is refused,
    unless `replace`, it is a sample this generator wrote and it holds only the files its manifest lists. Fail closed:
    the old sample is moved aside, the complete new one moved in, and the old one is put back if that fails."""
    if project_dir is None:
        from env.lock import PROJECT_DIR

        project_dir = PROJECT_DIR
    out, formal = Path(out), Path(project_dir) / "data" / "external"
    if inside(out, formal):
        raise PermissionError(f"the synthetic sample must be outside {formal.resolve()} (it is never part of any set)")
    if out.exists() and not (replace and is_sample(out)):
        raise FileExistsError(f"{out} exists" + (" and is not a sample written by collect.sample" if replace else
                                                 " (pass replace to regenerate a sample)"))
    if out.exists() and (unlisted := unlisted_files(out)):
        raise FileExistsError(f"{out} holds files not listed in its {SAMPLE_FILE}, which a replace would delete: {unlisted}")
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp, old = (out.parent / f".{out.name}.{what}-{os.getpid()}" for what in ("tmp", "old"))
    for leftover in (tmp, old):  # an unfinished attempt of this process
        if leftover.exists():
            shutil.rmtree(leftover)
    moved = False
    try:
        tmp.mkdir()
        _write(tmp)
        if out.exists():
            os.replace(out, old)
            moved = True
        os.replace(tmp, out)
    except BaseException:
        if moved and not out.exists():
            os.replace(old, out)
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    if moved:
        shutil.rmtree(old)
    return json.loads((out / SAMPLE_FILE).read_text())
