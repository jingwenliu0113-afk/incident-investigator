SAMPLE_DIR = Path("data/samples/synthetic")
SAMPLE_FILE = "sample.json"
OS_FILES = frozenset({".DS_Store"})  # what Finder writes into any folder it opens; gitignored, never part of a sample
# next_id starts at 001, so 000 never names a collected run group or incident; collect calibrate also writes its soak
# snapshots (no fault, in no set, under data/external/calibration/) as INC-000, so the id alone does not mean synthetic
INCIDENT, RUN_GROUP = "INC-000", "RG-000"
SEED = 0
WINDOW = ("2000-01-01T00:00:00Z", "2000-01-01T00:28:00Z")  # a date no collection has; data clock = host clock
FAULT_ON, FAULT_OFF = "2000-01-01T00:12:00Z", "2000-01-01T00:22:00Z"  # 12 normal, 10 fault, 6 recovery minutes
FLAG, VARIANT = "paymentFailure", "100%"  # the fault the generated pattern imitates (its decision 016 catalog entry)
ENVIRONMENT = "synthetic-sample"  # on every resource and in every scope name the canonical formats keep
PREDICTION = Path("predictions/stat-anomaly") / f"{INCIDENT}.json"
NOTE = ("SYNTHETIC sample (decision 027): generated by collect.sample from code, never collected; "
        "not a Pilot or held-out incident, and nothing computed on it is a result.")

S, MS = 10**9, 10**6
MINUTES = 28
FAULT_MINUTES = range(12, 22)
_LOYALTY_ERROR = "Payment request failed. Invalid token. app.loyalty.level=gold"


# ------------------------------------------------------------------ raw OTLP JSON


def _digest(*parts) -> bytes:
    return hashlib.blake2b(":".join(map(str, parts)).encode(), digest_size=16, person=b"ii-sample").digest()


def _hex(length: int, *parts) -> str:
    return _digest(*parts).hex()[:length]


def _pick(lo: int, hi: int, *parts) -> int:
    """A fixed integer in [lo, hi] (blake2b, not `random`: the same bytes on every Python version)."""
    return lo + int.from_bytes(_digest(*parts)[:8], "big") % (hi - lo + 1)


def _kv(attrs: dict) -> list:
    return [{"key": k, "value": {"intValue": str(v)} if isinstance(v, int) else {"stringValue": v}}
            for k, v in attrs.items()]


def _resource(service: str, key: str = "service.name") -> dict:
    return {"attributes": _kv({key: service, "deployment.environment.name": ENVIRONMENT})}


def _start_ns() -> int:
    from collect.normalize import host_to_data_ns

    return host_to_data_ns(WINDOW[0], 0.0)


# Span attribute keys are the ones each service sends in real soaks (the frozen policy's attribute_key_inventory, decision
# 027 §4): Envoy's http.* tags at frontend-proxy, rpc.system.name at checkout / product-catalog, grpc.* at cart (.NET),
# rpc.system / rpc.service at payment. The only key real snapshots lack is the deployment.environment.name marker.
_ENVOY = "http://frontend-proxy:8080"


def _browse(minute: int) -> tuple:
    """(service, name, OTLP kind, attributes, self time ms, children): one product page."""
    product = ("OLJCESPC7Z", "66VCHSJNUP", "1YMWWN1N4O", "L9ECAV7KIM")[minute % 4]
    return ("load-generator", "GET", 3, {}, 1, [
        ("frontend-proxy", "ingress", 2, {"http.method": "GET", "http.url": f"{_ENVOY}/api/products/{product}"}, 1, [
            ("frontend", "GET /api/products/[productId]", 2,
             {"http.request.method": "GET", "url.path": f"/api/products/{product}"}, 6, [
                ("product-catalog", "oteldemo.ProductCatalogService/GetProduct", 2,
                 {"rpc.system.name": "grpc", "rpc.method": "oteldemo.ProductCatalogService/GetProduct"}, 2, [])])])])


def _checkout(fault: bool) -> tuple:
    """One order: while the fault is on, payment refuses the charge and the error climbs to the edge."""
    def go(method: str) -> dict:
        return {"rpc.system.name": "grpc", "rpc.method": method}

    return ("load-generator", "POST", 3, {}, 1, [
        ("frontend-proxy", "ingress", 2, {"http.method": "POST", "http.url": f"{_ENVOY}/api/checkout"}, 1, [
            ("frontend", "POST /api/checkout", 2, {"http.request.method": "POST", "url.path": "/api/checkout"}, 6, [
                ("checkout", "oteldemo.CheckoutService/PlaceOrder", 2, go("oteldemo.CheckoutService/PlaceOrder"), 3, [
                    ("checkout", "oteldemo.CartService/GetCart", 3, go("oteldemo.CartService/GetCart"), 1, [
                        ("cart", "oteldemo.CartService/GetCart", 2, {"grpc.method": "/oteldemo.CartService/GetCart"}, 2, [])]),
                    ("checkout", "oteldemo.PaymentService/Charge", 3, go("oteldemo.PaymentService/Charge"), 1, [
                        ("payment", "oteldemo.PaymentService/Charge", 2,
                         {"rpc.system": "grpc", "rpc.service": "oteldemo.PaymentService", "rpc.method": "Charge"},
                         1 if fault else 4, [])])])])])])


def _status(service: str, kind: int, failed: bool) -> dict:
    if not failed:
        return {}
    message = {("payment", 2): _LOYALTY_ERROR,
               ("checkout", 3): f"rpc error: code = Unknown desc = {_LOYALTY_ERROR}",
               ("checkout", 2): f"failed to charge card: could not charge the card: rpc error: code = Unknown desc = "
                                f"{_LOYALTY_ERROR}"}.get((service, kind))
    return {"code": 2, "message": message} if message else {"code": 2}


def _build(node: tuple, trace: str, path: str, start: int, parent: str | None, fault: bool, out: list) -> tuple[int, bool]:
    """Append (service, span) for `node` and its subtree; returns the span's end and whether it failed."""
    service, name, kind, attrs, self_ms, children = node
    span_id = _hex(16, trace, path)
    cursor, failed = start + 200_000, False
    for i, child in enumerate(children):
        cursor, child_failed = _build(child, trace, f"{path}.{i}", cursor + 100_000, span_id, fault, out)
        failed |= child_failed
    failed |= fault and service == "payment"
    end = cursor + self_ms * MS + _pick(0, self_ms * MS // 3, trace, path, "self")
    if kind == 2 and "http.request.method" in attrs:
        attrs = {**attrs, "http.response.status_code": 500 if failed else 200}
    elif kind == 2 and "http.method" in attrs:  # Envoy's tags are strings
        attrs = {**attrs, "http.status_code": "500" if failed else "200"}
    span = {"traceId": trace, "spanId": span_id, "name": name, "kind": kind, "startTimeUnixNano": str(start),
            "endTimeUnixNano": str(end), "attributes": _kv(attrs), "status": _status(service, kind, failed)}
    if parent:
        span["parentSpanId"] = parent
    if service == "payment":  # the SDK records every flag evaluation; normalize removes it (X5, decision 011)
        span["events"] = [{"timeUnixNano": str(start + 50_000), "name": "feature_flag.evaluation",
                           "attributes": _kv({"feature_flag.key": FLAG, "feature_flag.result.variant": VARIANT if fault else "off"})}]
    out.append((service, span))
    return end, failed


def _lines(by_service: dict[str, list], top: str, scoped: str, items: str, scope: str = ENVIRONMENT) -> str:
    """One OTLP JSON line (an exporter batch) with a resource per service, in a fixed order."""
    key = "container.name" if "Metrics" in top else "service.name"
    return json.dumps({top: [{"resource": _resource(svc, key), scoped: [{"scope": {"name": scope}, items: records}]}
                             for svc, records in sorted(by_service.items())]}, sort_keys=True)


def raw_lines() -> dict[str, list[str]]:
    """Per signal, the raw OTLP JSON lines of the whole window: one exporter batch per minute."""
    t0 = _start_ns()
    traces, logs, metrics = [], [], []
    cpu = {"payment": 0, "checkout": 0}
    for minute in range(MINUTES):
        fault = minute in FAULT_MINUTES
        base = t0 + minute * 60 * S
        spans: list = []
        _build(_browse(minute), _hex(32, "browse", minute), "0", base + _pick(5, 15, "browse", minute) * S, None, False,
               spans)
        order = _hex(32, "checkout", minute)
        _build(_checkout(fault), order, "0", base + _pick(25, 45, "checkout", minute) * S, None, fault, spans)
        by_service: dict[str, list] = {}
        for svc, span in spans:
            by_service.setdefault(svc, []).append(span)
        traces.append(_lines(by_service, "resourceSpans", "scopeSpans", "spans"))

        charge = next(span for svc, span in spans if svc == "payment")
        place = next(span for svc, span in spans if svc == "checkout" and span["kind"] == 2)
        records = {"payment": [_log(charge, 17 if fault else 9, _LOYALTY_ERROR if fault else "Transaction complete.")]}
        if fault:
            records["checkout"] = [_log(place, 17, place["status"]["message"])]
        logs.append(_lines(records, "resourceLogs", "scopeLogs", "logRecords"))

        t = base + 45 * S
        points: dict[str, list] = {}
        for svc, cores_milli, mib in (("payment", 40, 96), ("checkout", 70, 48)):
            cpu[svc] += 60 * _pick(cores_milli - 2, cores_milli + 2, svc, minute, "cpu") * MS  # ns of CPU per minute
            memory = mib * 2**20 + _pick(0, 2**18, svc, minute, "memory")
            points[svc] = [
                {"name": "container.cpu.usage.total", "unit": "ns",
                 "sum": {"aggregationTemporality": 2, "isMonotonic": True,
                         "dataPoints": [{"startTimeUnixNano": str(t0 - 300 * S), "timeUnixNano": str(t),
                                         "asInt": str(cpu[svc]), "attributes": []}]}},
                {"name": "container.memory.usage.total", "unit": "By",
                 "gauge": {"dataPoints": [{"timeUnixNano": str(t), "asInt": str(memory), "attributes": []}]}}]
        metrics.append(_lines(points, "resourceMetrics", "scopeMetrics", "metrics",
                              scope=f"{ENVIRONMENT}/dockerstatsreceiver"))
    return {"traces": traces, "metrics": metrics, "logs": logs}


def _log(span: dict, severity: int, body: str) -> dict:
    t = str(int(span["endTimeUnixNano"]) - 100_000)
    return {"timeUnixNano": t, "observedTimeUnixNano": t, "severityNumber": severity,
            "severityText": "ERROR" if severity >= 17 else "INFO", "body": {"stringValue": body}, "attributes": [],
            "traceId": span["traceId"], "spanId": span["spanId"]}


def write_raw(raw_dir: Path) -> dict[str, Path]:
    raw_dir.mkdir(parents=True, exist_ok=True)
    out = {}
    for sig, lines in raw_lines().items():
        out[sig] = raw_dir / f"{sig}.jsonl"
        out[sig].write_text("\n".join(lines) + "\n")
    return out


